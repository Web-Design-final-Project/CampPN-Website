eq('full wins over closed', L.eventStatus(ev, 0, utc('2026-10-20T00:00:00Z')), 'full');
eq('ongoing', L.eventStatus(ev, 6, utc('2026-10-24T12:00:00Z')), 'ongoing');
eq('completed', L.eventStatus(ev, 6, utc('2026-10-24T14:31:00Z')), 'completed');
eq('seat info', L.seatInfo(ev, 2), { registered: 6, remaining: 4, capacity: 10, percent: 60 });
eq('seat info capped', L.seatInfo(ev, 99).remaining, 0);
